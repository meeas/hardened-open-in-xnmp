'use strict';

/** Generate the compiled caller allowlist from the same registry as the host.
 * Run without arguments to update; --check exits nonzero for a stale header.
 */
const fs = require('fs');
const path = require('path');
const config = require('../app/config');
const filename = path.join(__dirname, '../app/shim-allowlist.h');
const content = '/* Generated by scripts/generate-shim-allowlist.js; do not edit. */\n' +
  ['chromium', 'mozilla'].map(mode => {
    const entries = config.extensions.filter(e => (e.store === 'firefox') === (mode === 'mozilla'));
    return `static const char *const ${mode}_callers[] = {\n` +
      entries.map(e => `    ${JSON.stringify(config.identity(e))},`).join('\n') + '\n};\n';
  }).join('\n');
if (process.argv[2] === '--check') {
  if (fs.readFileSync(filename, 'utf8') !== content) {
    console.error('Stale shim allowlist; regenerate and rebuild the shim.');
    process.exitCode = 1;
  }
}
else if (process.argv.length !== 2) throw new Error('Usage: node scripts/generate-shim-allowlist.js [--check]');
else fs.writeFileSync(filename, content);
